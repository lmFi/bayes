function [nuclei_depths, nuclei_vs, forward_model, like, npt, Num] = ...
    baseline_RJ_C_mian(nuclei_vs, nuclei_depths, like, npt, priors, sigma, s, ...
    Num, out, data_mode, fit_error, beta, x, forward_model_current)
%RJ_C_MIAN Apply one reversible-jump proposal to a complete chain state.

    if nargin < 14
        forward_model_current = [];
    end
    forward_model_current = ensure_forward_model(forward_model_current, ...
        nuclei_depths, nuclei_vs, npt, priors, data_mode, fit_error, like);

    if mod(s, 2) == 0
        [nuclei_depths, nuclei_vs, forward_model, like, npt, Num] = ...
            Change(nuclei_vs, nuclei_depths, like, npt, priors, sigma, ...
            Num, out, data_mode, fit_error, beta, x, forward_model_current);
        return;
    end

    [p_birth, p_death, ~] = rj_operation_probabilities(npt, priors);
    u = rand;
    if u < p_birth
        [nuclei_depths, nuclei_vs, forward_model, like, npt, Num] = ...
            baseline_Birth(nuclei_vs, nuclei_depths, like, npt, priors, sigma, ...
            Num, out, data_mode, fit_error, beta, x, forward_model_current);
    elseif u < p_birth + p_death
        [nuclei_depths, nuclei_vs, forward_model, like, npt, Num] = ...
            baseline_Death(nuclei_vs, nuclei_depths, like, npt, priors, sigma, ...
            Num, out, data_mode, fit_error, beta, forward_model_current);
    else
        [nuclei_depths, nuclei_vs, forward_model, like, npt, Num] = ...
            Move(nuclei_vs, nuclei_depths, like, npt, priors, sigma, ...
            Num, out, data_mode, fit_error, beta, forward_model_current);
    end
end

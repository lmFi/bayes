function [h_region, h_boundary] = add_burnin_region(ax, burn_in, nsample)
%ADD_BURNIN_REGION Shade burn-in iterations and mark their end.

    y_limits = ylim(ax);
    if strcmpi(ax.YScale, 'log') && y_limits(1) <= 0
        y_limits(1) = eps;
    end

    hold_state = ishold(ax);
    hold(ax, 'on');
    h_region = patch(ax, ...
        [0 burn_in burn_in 0], ...
        [y_limits(1) y_limits(1) y_limits(2) y_limits(2)], ...
        [0.93 0.95 0.97], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.90, ...
        'DisplayName', 'Burn-in samples');
    try
        uistack(h_region, 'bottom');
    catch
        % uistack is unavailable in a small number of older MATLAB builds.
    end
    h_boundary = xline(ax, burn_in, '--', ...
        sprintf('Burn-in ends (%d)', burn_in), ...
        'Color', [0.85 0.42 0.02], ...
        'LineWidth', 1.5, ...
        'LabelOrientation', 'horizontal', ...
        'LabelVerticalAlignment', 'bottom', ...
        'HandleVisibility', 'off');
    xlim(ax, [0 nsample]);
    ylim(ax, y_limits);

    if ~hold_state
        hold(ax, 'off');
    end
end

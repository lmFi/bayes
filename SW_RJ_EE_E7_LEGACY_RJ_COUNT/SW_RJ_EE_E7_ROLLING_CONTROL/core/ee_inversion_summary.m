function s=ee_inversion_summary(r,Model,x,cfg,seconds,forward,ee)

% Raw posterior summaries. No smoothing, no claim of independent samples.

    L=(numel(Model)+1)/2;
    velocities=Model(1:L);
    boundaries=cumsum(Model(L+1:end));

    truth=zeros(1,numel(x));

    for j=1:numel(x)
        truth(j)=velocities(1+sum(x(j)>=boundaries));
    end

    kept=r.vs_all;

    qs=quantile(kept,[.025 .975],1);

    en=r.cov(cfg.burn_in+1:end);

    k=r.nnuclei(cfg.burn_in+1:end);

    mid=floor(numel(k)/2);
    edges=(cfg.npt_min+1-.5):(cfg.npt_max+1+.5);

    drift=NaN;

    if mid>0
        p=histcounts(k(1:mid),edges,'Normalization','probability');
        q=histcounts(k(mid+1:end),edges,'Normalization','probability');
        drift=.5*sum(abs(p-q));
    end

    % ---------------------------------------------------------
    % EE summary
    %
    % Single-chain runs or EE-disabled runs have no EE chain pair.
    % Therefore ee may be an empty table.
    % ---------------------------------------------------------
    cold_EE_selected = 0;
    cold_EE_accepted = 0;
    cold_EE_available_fraction = NaN;
    cold_EE_posterior_accepted = 0;

    has_ee_pair = cfg.enable_ee && ...
                  numel(cfg.temperatures) >= 2 && ...
                  ~isempty(ee) && ...
                  height(ee) >= 1;

    if has_ee_pair
        cold_EE_selected = ee.Selected(1);
        cold_EE_accepted = ee.Accepted(1);
        cold_EE_available_fraction = ee.AvailableFraction(1);
        cold_EE_posterior_accepted = ee.PosteriorAccepted(1);
    end

    s=struct( ...
        'case_name',string(cfg.case_name), ...
        'run_label',string(cfg.run_label), ...
        'seed',cfg.seed, ...
        'EE',cfg.enable_ee, ...
        'A',cfg.enable_a, ...
        'update_mode',string('local_rj_then_optional_ee'), ...
        'seconds',seconds, ...
        'retained',size(kept,1), ...
        'posterior_min_energy',min(en), ...
        'posterior_mean_energy',mean(en), ...
        'posterior_mean_K',mean(k), ...
        'posterior_K_switches',sum(diff(k)~=0), ...
        'K_half_TV',drift, ...
        'raw_mean_Vs_RMSE_mps',sqrt(mean((mean(kept,1)-truth).^2)), ...
        'truth_grid_coverage95',mean(truth>=qs(1,:) & truth<=qs(2,:)), ...
        'forward_calls',forward.calls, ...
        'forward_missing',forward.missing_prediction, ...
        'forward_exceptions',forward.exception, ...
        'cold_EE_selected',cold_EE_selected, ...
        'cold_EE_accepted',cold_EE_accepted, ...
        'cold_EE_available_fraction',cold_EE_available_fraction, ...
        'cold_EE_posterior_accepted',cold_EE_posterior_accepted);

end
function [summary,events,calibration]=ee_result_tables(EE,burn_in)
% All accepted/rejected selected EE events; raw values, no convergence claim.
    C=EE.nchains-1;
    a=zeros(C,18);
    for t=1:C
        sel=EE.jump_history(:,t)~=0;
        valid=abs(EE.jump_history(:,t))==1;
        acc=EE.jump_history(:,t)==1;
        post=(1:EE.nsample).'>burn_in;
        d=EE.profile_rms_delta(acc,t); d=d(isfinite(d));
        med=NaN; if ~isempty(d), med=median(d); end
        local_delta=EE.energy_after_local(:,t)-EE.energy_before_local(:,t);
        ee_delta=EE.energy_after_ee(:,t)-EE.energy_after_local(:,t);
        local_npt_change=EE.npt_after_local(:,t)~=EE.npt_before_local(:,t);
        ee_npt_change=EE.npt_after_ee(:,t)~=EE.npt_after_local(:,t);
        a(t,:)=[t t+1 sum(sel) sum(sel & ~valid) sum(valid) sum(acc) ...
            safe_ratio(sum(valid),sum(sel)) safe_ratio(sum(acc),sum(valid)) ...
            safe_ratio(sum(acc),sum(sel)) EE.jump_crossdim_proposed(t) ...
            EE.jump_crossdim_accepted(t) sum(sel & post) sum(acc & post) med ...
            finite_median(local_delta) finite_median(ee_delta(sel)) ...
            safe_ratio(sum(local_npt_change),sum(isfinite(EE.npt_before_local(:,t)))) ...
            safe_ratio(sum(ee_npt_change & sel),sum(sel))];
    end
    summary=array2table(a,'VariableNames',{'Recipient','Donor','Selected','Unavailable', ...
        'Valid','Accepted','AvailableFraction','AcceptedPerValid','AcceptedPerSelected', ...
        'CrossProposed','CrossAccepted','PosteriorSelected','PosteriorAccepted','MedianAcceptedProfileRMS_mps', ...
        'MedianLocalEnergyDelta','MedianSelectedEEEnergyDelta','LocalNptChangeFraction','SelectedEENptChangeFraction'});
    [s,t]=find(EE.jump_history~=0); idx=sub2ind(size(EE.jump_history),s,t);
    pre_local=sub2ind(size(EE.energy_before_local),s,t);
    post_local=sub2ind(size(EE.energy_after_local),s,t);
    post_ee=sub2ind(size(EE.energy_after_ee),s,t);
    values=[s t t+1 double(EE.jump_history(idx)) double(EE.unavailable_reason(idx)) ...
        EE.selected_ring(idx) EE.donor_count_at_selection(idx) ...
        EE.current_npt(idx) EE.candidate_npt(idx) EE.current_energy(idx) ...
        EE.candidate_energy(idx) EE.log_acceptance(idx) EE.candidate_iteration(idx) ...
        s-EE.candidate_iteration(idx) EE.profile_rms_delta(idx) EE.profile_max_delta(idx) ...
        EE.energy_before_local(pre_local) EE.energy_after_local(post_local) ...
        EE.energy_after_ee(post_ee) EE.npt_before_local(pre_local) ...
        EE.npt_after_local(post_local) EE.npt_after_ee(post_ee)];
    events=array2table(values,'VariableNames',{'Iteration','Recipient','Donor','Outcome', ...
        'UnavailableReason','Ring','DonorEntries','CurrentNpt','CandidateNpt','CurrentEnergy', ...
        'CandidateEnergy','LogAccept','CandidateIteration','CandidateAge','ProfileRMS_mps','ProfileMax_mps', ...
        'EnergyBeforeLocal','EnergyAfterLocal','EnergyAfterEE','NptBeforeLocal','NptAfterLocal','NptAfterEE'});
    if isfield(EE,'edge_epoch_history')
        events.EdgeEpoch=double(EE.edge_epoch_history(s));
    end
    events=sortrows(events,{'Iteration','Recipient'});
    rows=zeros(0,9);
    for r=1:C
        if isempty(EE.calibration_report{r}), continue; end
        cr=EE.calibration_report{r}; B=numel(cr.edges)-1;
        for b=1:B
            rows(end+1,:)=[r r+1 b cr.edges(b) cr.edges(b+1) cr.recipient_count(b) ...
                cr.donor_count(b) cr.initial_nbins cr.final_nbins]; %#ok<AGROW>
        end
    end
    calibration=array2table(rows,'VariableNames',{'Recipient','Donor','Ring','LeftEnergy', ...
        'RightEnergy','RecipientPilotEntries','DonorPilotEntries','InitialRingCount','FinalRingCount'});
end
function v=safe_ratio(a,b)
    v=NaN; if b>0, v=a/b; end
end
function v=finite_median(x)
    x=x(isfinite(x));
    v=NaN; if ~isempty(x), v=median(x); end
end

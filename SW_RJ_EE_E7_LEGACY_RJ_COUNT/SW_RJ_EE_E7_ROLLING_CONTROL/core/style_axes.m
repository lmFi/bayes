function style_axes(ax, show_grid)
%STYLE_AXES Apply one consistent publication-style axis format.

    if nargin < 2
        show_grid = true;
    end

    set(ax, ...
        'Box', 'on', ...
        'LineWidth', 0.9, ...
        'Layer', 'top', ...
        'TickDir', 'in', ...
        'TickLength', [0.012 0.012], ...
        'XMinorTick', 'off', ...
        'YMinorTick', 'off', ...
        'XColor', [0.10 0.10 0.10], ...
        'YColor', [0.10 0.10 0.10], ...
        'FontName', 'Times New Roman', ...
        'FontSize', 11);

    if show_grid
        grid(ax, 'on');
        set(ax, 'GridColor', [0.86 0.89 0.93], ...
            'GridAlpha', 0.55, 'GridLineStyle', '-');
    else
        grid(ax, 'off');
    end
end

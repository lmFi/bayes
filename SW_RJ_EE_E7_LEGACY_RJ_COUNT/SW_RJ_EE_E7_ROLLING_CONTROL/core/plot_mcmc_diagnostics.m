function plot_mcmc_diagnostics(result, variable, priors, Model, ...
    burn_in, nsample)
%PLOT_MCMC_DIAGNOSTICS Plot traces and normalized posterior summaries.
% Trace panels contain every iteration.  Posterior panels contain only the
% retained cold-chain samples collected after burn-in and thinning.

    blue = [0.137 0.357 0.651];
    teal = [0.059 0.463 0.431];
    orange = [0.850 0.420 0.020];
    light_orange = [0.914 0.635 0.231];

    [true_nuclei, true_interfaces] = true_model_metadata(Model);
    iterations = (1:nsample).';

    fig = figure('Color', 'w', 'Name', 'MCMC diagnostics', ...
        'Position', [100 80 1320 820]);
    layout = tiledlayout(fig, 2, 2, ...
        'TileSpacing', 'compact', 'Padding', 'compact');

    %% (a) Negative log-likelihood / data-misfit energy
    ax1 = nexttile(layout, 1);
    valid_energy = isfinite(result.cov) & result.cov > 0;
    semilogy(ax1, iterations(valid_energy), result.cov(valid_energy), ...
        'Color', blue, 'LineWidth', 0.8);
    xlabel(ax1, 'Iteration');
    ylabel(ax1, 'Data-misfit energy E(m)');
    title(ax1, '(a) Negative log-likelihood trace');
    style_axes(ax1, true);
    [h_burn, ~] = add_burnin_region(ax1, burn_in, nsample);
    legend(ax1, h_burn, 'Burn-in samples', ...
        'Location', 'northeast', 'Box', 'off', 'FontSize', 9);

    %% (b) Total model dimension
    ax2 = nexttile(layout, 2);
    plot(ax2, iterations, result.nnuclei, ...
        'Color', teal, 'LineWidth', 0.75);
    xlabel(ax2, 'Iteration');
    ylabel(ax2, 'Total number of nuclei K');
    title(ax2, '(b) Model-dimension trace');
    ylim(ax2, [0 priors.npt_max + priors.num_layers + 0.5]);
    style_axes(ax2, true);
    [h_burn2, ~] = add_burnin_region(ax2, burn_in, nsample);
    legend(ax2, h_burn2, 'Burn-in samples', ...
        'Location', 'northeast', 'Box', 'off', 'FontSize', 9);

    %% (c) Posterior density of interface depth
    ax3 = nexttile(layout, 3);
    hold(ax3, 'on');
    if variable.counter_auxiliary > 0
        interface_samples = result.change_points(1:variable.counter_auxiliary);
        interface_samples = interface_samples(isfinite(interface_samples));
        histogram(ax3, interface_samples, ...
            'BinWidth', 0.25, ...
            'BinLimits', [0 priors.depth_max], ...
            'Normalization', 'pdf', ...
            'FaceColor', light_orange, ...
            'EdgeColor', orange, ...
            'FaceAlpha', 0.88, ...
            'LineWidth', 0.45);
    end
    for i = 1:numel(true_interfaces)
        xline(ax3, true_interfaces(i), ':', ...
            'Color', [0.48 0.55 0.65], ...
            'LineWidth', 1.0, ...
            'HandleVisibility', 'off');
    end
    xlabel(ax3, 'Interface depth (m)');
    ylabel(ax3, 'Probability density (m^{-1})');
    title(ax3, '(c) Posterior density of interface depth');
    xlim(ax3, [0 priors.depth_max]);
    style_axes(ax3, true);

    %% (d) Posterior probability of the number of nuclei
    ax4 = nexttile(layout, 4);
    count_by_dimension = result.nnucleihist(:);
    retained_count = sum(count_by_dimension);
    if retained_count > 0
        probability_by_dimension = count_by_dimension ./ retained_count;
    else
        probability_by_dimension = zeros(size(count_by_dimension));
    end
    nuclei_values = (1:numel(probability_by_dimension)).';
    bar(ax4, nuclei_values, probability_by_dimension, 0.82, ...
        'FaceColor', [0.36 0.56 0.82], ...
        'EdgeColor', blue, ...
        'LineWidth', 0.8);
    hold(ax4, 'on');
    xline(ax4, true_nuclei, '--', ...
        sprintf('True model: K = %d', true_nuclei), ...
        'Color', orange, ...
        'LineWidth', 1.5, ...
        'LabelOrientation', 'horizontal', ...
        'LabelVerticalAlignment', 'top');
    xlabel(ax4, 'Total number of nuclei K');
    ylabel(ax4, 'Posterior probability');
    title(ax4, '(d) Posterior probability of model dimension');
    xlim(ax4, [0.4 numel(probability_by_dimension) + 0.6]);
    xticks(ax4, 1:2:numel(probability_by_dimension));
    ylim(ax4, [0 max(0.05, 1.12 * max(probability_by_dimension))]);
    style_axes(ax4, true);

    title(layout, 'MCMC convergence and posterior-dimension diagnostics', ...
        'FontName', 'Times New Roman', 'FontSize', 16, ...
        'FontWeight', 'bold', 'Color', [0.09 0.15 0.33]);

    annotation(fig, 'textbox', [0.20 0.002 0.60 0.035], ...
        'String', ['Panels (c)-(d) use retained cold-chain samples ' ...
                   'after burn-in and thinning.'], ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'EdgeColor', 'none', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 9, ...
        'Color', [0.38 0.45 0.55]);
end
